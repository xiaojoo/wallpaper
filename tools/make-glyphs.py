def bits(rows):
    v = 0
    for r, row in enumerate(rows):
        for c, px in enumerate(row):
            if px == '#':
                v |= 1 << (r * 5 + c)
    return v

ORDER = sorted(G, key=ord)
print('\n// index = ASCII - 32, so GLYPH[ch-32]. The degree sign is not printable ASCII on this path,')
print('// so it is parked at code 127 (index 95) and shaders spell it as the kDeg constant.')
vals = []
for i in range(32, 128):
    ch = chr(i)
    if i == 127:
        vals.append(bits(G['°']))
    else:
        vals.append(bits(G[ch]) if ch in G else 0)
for k in range(0, len(vals), 5):
    print('    ' + ', '.join('%du' % v for v in vals[k:k + 5]) + ',')

# Render the sheet so the shapes can actually be looked at.
S, PAD = 7, 3
cols = 12
rows = (len(ORDER) + cols - 1) // cols
W = cols * (5 * S + PAD * S) + PAD * S
H = rows * (6 * S + PAD * S) + PAD * S
img = [[0] * W for _ in range(H)]
for n, ch in enumerate(ORDER):
    ox = PAD * S + (n % cols) * (5 * S + PAD * S)
    oy = PAD * S + (n // cols) * (6 * S + PAD * S)
    for r, row in enumerate(G[ch]):
        for c, px in enumerate(row):
            if px == '#':
                for dy in range(S):
                    for dx in range(S):
                        img[oy + r * S + dy][ox + c * S + dx] = 255
from PIL import Image
Image.frombytes('L', (W, H), bytes(v for row in img for v in row)).resize((W * 2, H * 2)).save(
    'tools/tmp/glyph-sheet.png')
print('\nsheet: tools/tmp/glyph-sheet.png  order:', ''.join(c if c != ' ' else '_' for c in ORDER))
